// Escreva um programa que escreva na tela os número de 15 até 20.

#include "stdafx.h"
#include "stdlib.h"


int main()
{
	int cont;

	for (cont = 15;cont < 21;cont++)
	{
		printf("%d \n", cont);
	}
	system("pause");
    return 0;
}

